import { plantFlaws, scoreLint } from "../src/benchmark.ts";
import { acquisitionScenario } from "../src/fixtures/acquisition.ts";
import { lintScenario } from "../src/lint.ts";

// Usage: npm run benchmark [-- --missed]
const cases = plantFlaws(acquisitionScenario);
const score = scoreLint(acquisitionScenario, cases, lintScenario);
const pct = (part, whole) => whole ? `${Math.round((part / whole) * 100)}%` : "–";
const lines = [
  "# Planted-flaw benchmark (fictional files)",
  "",
  `${cases.length} copies of the clean campaign, each with exactly one planted mistake.`,
  "“Caught” means a finding points at the planted file and fact. Findings anywhere else count as stray alarms.",
  "",
  `${"Flaw type".padEnd(22)}${"Planted".padStart(8)}${"Caught".padStart(8)}${"Rate".padStart(7)}${"Stray".padStart(7)}`
];
for (const row of score.byKind) {
  lines.push(`${row.kind.padEnd(22)}${String(row.planted).padStart(8)}${String(row.caught).padStart(8)}${pct(row.caught, row.planted).padStart(7)}${String(row.strayFindings).padStart(7)}`);
}
const planted = score.byKind.reduce((total, row) => total + row.planted, 0);
const caught = score.byKind.reduce((total, row) => total + row.caught, 0);
lines.push("", `Total: ${caught}/${planted} caught (${pct(caught, planted)}). False alarms on the clean files: ${score.cleanFalseAlarms}.`);
if (process.argv.includes("--missed")) {
  lines.push("", "## Missed");
  for (const row of score.byKind) for (const id of row.missed) lines.push(`- ${id}: ${cases.find(item => item.id === id).description}`);
}
lines.push("", "The flaws are generated by the same author as the lint, so this measures coverage of known mistake types, not real-world accuracy.");
process.stdout.write(`${lines.join("\n")}\n`);
